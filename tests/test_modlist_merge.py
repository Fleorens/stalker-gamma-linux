class TestFinsDeLigne:
    def test_le_crlf_de_lamont_est_preserve(self) -> None:
        """L'instance MO2 vient de Windows : `modlist.txt` y est en CRLF."""
        base = _list("+A", "+B", newline="\r\n")
        ours = _list("+A", "-B", newline="\r\n")
        theirs = _list("+A", "+B", "+C", newline="\r\n")

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert "\r\n" in outcome.text
        assert outcome.text.count("\r\n") == len(outcome.text.splitlines())
        assert "\n" not in outcome.text.replace("\r\n", "")

    def test_un_amont_en_lf_reste_en_lf_meme_si_le_joueur_est_en_crlf(self) -> None:
        outcome = modlist_merge.merge_modlists(
            _list("+A", "+B"), _list("+A", "-B", newline="\r\n"), _list("+A", "+B")
        )

        assert outcome.merged
        assert outcome.text is not None
        assert "\r" not in outcome.text

    def test_len_tete_amont_est_conserve(self) -> None:
        outcome = modlist_merge.merge_modlists(_list("+A"), _list("-A"), _list("+A"))

        assert outcome.merged
        assert outcome.text is not None
        assert outcome.text.startswith("# This file was automatically generated")


class TestRapport:
    def test_le_rapport_annonce_les_trois_comptes(self) -> None:
        base = _list("+A", "+B", "+Retire", "+C")
        ours = _list("+A", "-B", "+MonMod", "+Retire", "+C")
        theirs = _list("+A", "+B", "+C")

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert (outcome.reactivated, outcome.deactivated) == (0, 1)
        assert outcome.reinserted == 1
        assert outcome.removed_upstream == 1
        assert "1 mod(s) re-enabled/disabled" in outcome.report
        assert "1 mod(s) you added put back in place" in outcome.report
        assert "1 entry(ies) removed upstream not restored" in outcome.report

    def test_une_fusion_sans_ecart_ne_change_rien(self) -> None:
        text = _list("+A", "+B")

        outcome = modlist_merge.merge_modlists(text, text, text)

        assert outcome.merged
        assert outcome.text == text
        assert not outcome.changed_anything


@pytest.mark.parametrize("newline", ["\n", "\r\n"])
def test_le_resultat_ne_contient_jamais_de_doublon(newline: str) -> None:
    """Invariant dur : un nom deux fois dans `modlist.txt` est un fichier corrompu."""
    base = _list("+A", "+B", "+C", "+D", "+E", newline=newline)
    ours = _list("+E", "+A", "+MonMod", "+B", "+C", newline=newline)
    theirs = _list("+A", "+C", "+B", "+F", newline=newline)

    outcome = modlist_merge.merge_modlists(base, ours, theirs)

    assert outcome.merged
    assert outcome.text is not None
    names = _names(outcome.text)
    assert len(names) == len(set(names))
    assert set(names) == {"A", "B", "C", "F", "MonMod"}
