"""Fusion à trois voies de `modlist.txt` — voir tasks/T17-sauvegarde-restauration-modlist.md.

Un test par règle du point 9 du prompt, plus la modlist vide et les fins de
ligne CRLF (l'instance MO2 vient de Windows). Tout est pur : trois chaînes
entrent, une chaîne sort.
"""

from __future__ import annotations

import pytest

from stalker_gamma_linux.mo2 import modlist_merge


def _list(*lines: str, newline: str = "\n") -> str:
    header = "# This file was automatically generated by Mod Organizer."
    return newline.join([header, *lines]) + newline


def _names(text: str) -> list[str]:
    return [entry.name for entry in modlist_merge.parse(text).entries]


def _markers(text: str) -> dict[str, str]:
    return {entry.name: entry.marker for entry in modlist_merge.parse(text).entries}


class TestParse:
    def test_garde_len_tete_les_entrees_et_les_fins_de_ligne(self) -> None:
        parsed = modlist_merge.parse(_list("+A", "-B", newline="\r\n"))

        assert parsed.header == ("# This file was automatically generated by Mod Organizer.",)
        assert parsed.names == ("A", "B")
        assert parsed.newline == "\r\n"
        assert parsed.trailing_newline is True

    def test_un_fichier_lf_reste_lf(self) -> None:
        assert modlist_merge.parse(_list("+A")).newline == "\n"

    def test_une_ligne_incomprise_apres_les_entrees_est_signalee(self) -> None:
        parsed = modlist_merge.parse("+A\n# note ajoutée à la main\n+B\n")

        assert parsed.stray == ("# note ajoutée à la main",)

    def test_les_lignes_vides_ne_sont_pas_des_anomalies(self) -> None:
        parsed = modlist_merge.parse("+A\n\n+B\n\n")

        assert parsed.stray == ()
        assert parsed.names == ("A", "B")


class TestEtatDesMods:
    """« N mods réactivés/désactivés selon tes réglages » — le cas central."""

    def test_une_desactivation_du_joueur_est_rejouee(self) -> None:
        base = _list("+A", "+B", "+C")
        ours = _list("+A", "-B", "+C")  # le joueur a désactivé B
        theirs = _list("+A", "+B", "+C", "+D")  # l'amont ajoute D

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert _markers(outcome.text)["B"] == "-"
        assert outcome.deactivated == 1
        assert outcome.reactivated == 0

    def test_une_reactivation_du_joueur_est_rejouee(self) -> None:
        outcome = modlist_merge.merge_modlists(
            _list("+A", "-B"), _list("+A", "+B"), _list("+A", "-B")
        )

        assert outcome.merged
        assert outcome.text is not None
        assert _markers(outcome.text)["B"] == "+"
        assert outcome.reactivated == 1

    def test_un_changement_amont_que_le_joueur_na_pas_touche_est_conserve(self) -> None:
        """Le joueur n'a rien dit sur B : c'est l'amont qui décide."""
        outcome = modlist_merge.merge_modlists(
            _list("+A", "+B"), _list("+A", "+B"), _list("+A", "-B")
        )

        assert outcome.merged
        assert outcome.text is not None
        assert _markers(outcome.text)["B"] == "-"
        assert outcome.deactivated == 0  # rien n'a été rejoué : ce n'est pas son réglage

    def test_le_marqueur_non_gere_nest_pas_transforme_en_active(self) -> None:
        """`*` = mod non géré par MO2 : en faire un `+` changerait le sens de la ligne."""
        outcome = modlist_merge.merge_modlists(
            _list("+A", "+B"), _list("+A", "*B"), _list("+A", "+B")
        )

        assert outcome.merged
        assert outcome.text is not None
        assert _markers(outcome.text)["B"] == "*"


class TestModsRetiresEnAmont:
    def test_un_mod_retire_en_amont_nest_jamais_ressuscite(self) -> None:
        """Son dossier n'existe plus sous `mods/` : MO2 l'afficherait en « missing »."""
        base = _list("+A", "+Retire", "+C")
        ours = _list("+A", "-Retire", "+C")  # le joueur l'avait même désactivé
        theirs = _list("+A", "+C")

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert "Retire" not in _names(outcome.text)
        assert outcome.removed_upstream == 1

    def test_une_entree_que_le_joueur_avait_retiree_reste_celle_de_lamont(self) -> None:
        """Supprimer une ligne que MO2 rajoutera seul n'est pas une décision de fusion."""
        outcome = modlist_merge.merge_modlists(
            _list("+A", "+B", "+C"), _list("+A", "+C"), _list("+A", "+B", "+C")
        )

        assert outcome.merged
        assert outcome.text is not None
        assert _names(outcome.text) == ["A", "B", "C"]
        assert outcome.kept_upstream_entries == 1


class TestModsAjoutesParLeJoueur:
    def test_un_ajout_est_reinsere_a_sa_position_relative(self) -> None:
        """« Auprès de son voisin conservé le plus proche », pas empilé en fin de liste."""
        base = _list("+A", "+B", "+C", "+D")
        ours = _list("+A", "+B", "+MonMod", "+C", "+D")
        theirs = _list("+A", "+B", "+C", "+D", "+NouveauAmont")

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert _names(outcome.text) == ["A", "B", "MonMod", "C", "D", "NouveauAmont"]
        assert outcome.reinserted == 1

    def test_un_ajout_dont_le_voisin_a_disparu_remonte_au_suivant(self) -> None:
        base = _list("+A", "+Voisin", "+C")
        ours = _list("+A", "+Voisin", "+MonMod", "+C")
        theirs = _list("+A", "+C")  # l'amont a retiré le voisin d'au-dessus

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert _names(outcome.text) == ["A", "MonMod", "C"]

    def test_un_groupe_dajouts_garde_son_ordre_interne(self) -> None:
        """Cas réel : une grappe d'ajouts en haut de liste, au-dessus du premier séparateur."""
        base = _list("+Fin_separator", "+A")
        ours = _list("+Un", "+Deux", "+Trois", "+Fin_separator", "+A")
        theirs = _list("+Fin_separator", "+A", "+B")

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert _names(outcome.text) == ["Un", "Deux", "Trois", "Fin_separator", "A", "B"]
        assert outcome.reinserted == 3


