class TestEnCasDeDouteOnNeFusionnePas:
    def test_un_meme_mod_deux_fois_fait_renoncer(self) -> None:
        outcome = modlist_merge.merge_modlists(
            _list("+A", "+B"), _list("+A", "+A", "+B"), _list("+A", "+B")
        )

        assert not outcome.merged
        assert outcome.text is None
        assert "twice" in outcome.reason

    def test_une_ligne_incomprise_fait_renoncer(self) -> None:
        ours = "+A\n# note ajoutée à la main\n+B\n"

        outcome = modlist_merge.merge_modlists(_list("+A", "+B"), ours, _list("+A", "+B"))

        assert not outcome.merged
        assert "does not understand" in outcome.reason

    def test_un_reordonnancement_concurrent_garde_lordre_amont(self) -> None:
        """Les deux côtés ont bougé la même région : l'amont gagne, et on le dit."""
        base = _list("+A", "+B", "+C", "+D")
        ours = _list("+A", "+C", "+B", "+D")  # le joueur intervertit B et C
        theirs = _list("+A", "+D", "+C", "+B")  # l'amont réordonne aussi

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert _names(outcome.text) == ["A", "D", "C", "B"]
        assert outcome.order_merged is False
        assert "kept as upstream wrote it" in outcome.report

    def test_un_reordonnancement_du_joueur_seul_est_conserve(self) -> None:
        """L'amont n'a pas touché cette région : rien n'oblige à jeter le travail du joueur."""
        base = _list("+A", "+B", "+C", "+D")
        ours = _list("+A", "+C", "+B", "+D")
        theirs = _list("+A", "+B", "+C", "+D", "+E")

        outcome = modlist_merge.merge_modlists(base, ours, theirs)

        assert outcome.merged
        assert outcome.text is not None
        assert _names(outcome.text) == ["A", "C", "B", "D", "E"]
        assert outcome.order_merged is True


